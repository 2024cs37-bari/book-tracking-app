import { zipSync } from 'fflate';
import { BACKUP_LIMITS } from './backup-validation';

/** Stored ZIP entries avoid decompression bombs and redundant compression of EPUB/PDF. */
export function buildBackupArchive(entries: Record<string, Uint8Array>): Blob {
  const size = Object.entries(entries).reduce(
    (sum, [name, bytes]) => sum + bytes.length + name.length * 2 + 100,
    22,
  );
  if (size > BACKUP_LIMITS.archiveBytes || Object.keys(entries).length > BACKUP_LIMITS.entries)
    throw new Error(
      'This portable backup exceeds the 128 MiB limit. Export metadata and keep your original files separately.',
    );
  const bytes = zipSync(entries, { level: 0 });
  return new Blob([new Uint8Array(bytes)], { type: 'application/zip' });
}

function crc32(bytes: Uint8Array): number {
  let crc = 0xffffffff;
  for (const byte of bytes) {
    crc ^= byte;
    for (let bit = 0; bit < 8; bit++) crc = (crc >>> 1) ^ (crc & 1 ? 0xedb88320 : 0);
  }
  return (crc ^ 0xffffffff) >>> 0;
}

/**
 * Parse only the bounded, non-encrypted, single-volume stored ZIP subset we emit.
 * No decompressor is invoked. All offsets, lengths, names, CRCs and duplicate
 * entries are checked before returning zero-copy byte views into the archive.
 */
export async function readBackupArchive(blob: Blob): Promise<Map<string, Uint8Array>> {
  if (blob.size > BACKUP_LIMITS.archiveBytes)
    throw new Error('Portable backup exceeds the 128 MiB limit.');
  const bytes = new Uint8Array(await blob.arrayBuffer());
  const view = new DataView(bytes.buffer);
  const fail = (): never => {
    throw new Error(
      'Invalid portable backup ZIP: damaged, compressed, encrypted or unsupported archive. Use the original backup generated by this app.',
    );
  };
  const end = bytes.length - 22;
  if (end < 0 || view.getUint32(end, true) !== 0x06054b50) fail();
  if (
    view.getUint16(end + 4, true) ||
    view.getUint16(end + 6, true) ||
    view.getUint16(end + 20, true)
  )
    fail();
  const count = view.getUint16(end + 10, true);
  if (count !== view.getUint16(end + 8, true) || count > BACKUP_LIMITS.entries) fail();
  let central = view.getUint32(end + 16, true);
  const centralStart = central;
  if (central + view.getUint32(end + 12, true) !== end) fail();
  const entries = new Map<string, Uint8Array>();
  const decoder = new TextDecoder('utf-8', { fatal: true });
  let localEnd = 0;
  for (let index = 0; index < count; index++) {
    if (central + 46 > end || view.getUint32(central, true) !== 0x02014b50) fail();
    const flags = view.getUint16(central + 8, true);
    const method = view.getUint16(central + 10, true);
    const crc = view.getUint32(central + 16, true);
    const compressed = view.getUint32(central + 20, true);
    const size = view.getUint32(central + 24, true);
    const nameSize = view.getUint16(central + 28, true);
    const extraSize = view.getUint16(central + 30, true);
    const commentSize = view.getUint16(central + 32, true);
    const local = view.getUint32(central + 42, true);
    if (
      flags & ~0x800 ||
      method !== 0 ||
      size !== compressed ||
      view.getUint16(central + 34, true) !== 0 ||
      local !== localEnd ||
      local + 30 > centralStart ||
      central + 46 + nameSize + extraSize + commentSize > end
    )
      fail();
    const name = decoder.decode(bytes.subarray(central + 46, central + 46 + nameSize));
    if (
      !/^(manifest\.json|metadata\.json|books\/[0-9a-f]{64}\.bin|covers\/[a-zA-Z0-9_-]+\.[a-z0-9]+)$/.test(
        name,
      ) ||
      entries.has(name)
    )
      fail();
    const limit = name.startsWith('books/')
      ? BACKUP_LIMITS.originalBytes
      : name.startsWith('covers/')
        ? BACKUP_LIMITS.coverBytes
        : BACKUP_LIMITS.metadataBytes;
    if (size > limit) throw new Error(`Backup entry ${name} exceeds its supported size limit.`);
    if (
      view.getUint32(local, true) !== 0x04034b50 ||
      view.getUint16(local + 6, true) !== flags ||
      view.getUint16(local + 8, true) !== method ||
      view.getUint32(local + 14, true) !== crc ||
      view.getUint32(local + 18, true) !== compressed ||
      view.getUint32(local + 22, true) !== size ||
      view.getUint16(local + 26, true) !== nameSize
    )
      fail();
    const localExtra = view.getUint16(local + 28, true);
    const dataStart = local + 30 + nameSize + localExtra;
    if (
      dataStart + size > centralStart ||
      decoder.decode(bytes.subarray(local + 30, local + 30 + nameSize)) !== name
    )
      fail();
    const data = bytes.subarray(dataStart, dataStart + size);
    if (crc32(data) !== crc) fail();
    entries.set(name, data);
    localEnd = dataStart + size;
    central += 46 + nameSize + extraSize + commentSize;
  }
  if (central !== end || localEnd !== centralStart) fail();
  return entries;
}
